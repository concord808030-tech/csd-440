function pdfText($text)
{
    $converted = iconv("UTF-8", "windows-1252//TRANSLIT", (string) $text);
    return $converted === false ? (string) $text : $converted;
}

class MiguelPDF extends FPDF
{
    public $tableName = "";
    public $columns = [];

    function Header()
    {
        $this->SetFillColor(31, 78, 121);
        $this->Rect(0, 0, $this->GetPageWidth(), 22, "F");
        $this->SetY(5);
        $this->SetTextColor(255, 255, 255);
        $this->SetFont("Helvetica", "B", 16);
        $this->Cell(0, 7, "Miguel's Video Game Collection", 0, 1, "L");
        $this->SetFont("Helvetica", "", 9);
        $this->Cell(0, 5, pdfText("Module 11.2 - Database data from Module 8 (table: {$this->tableName})"), 0, 1, "L");
        $this->SetTextColor(0, 0, 0);
        $this->SetY(28);
    }

    function Footer()
    {
        $this->SetY(-14);
        $this->SetDrawColor(31, 78, 121);
        $this->Line(10, $this->GetY(), $this->GetPageWidth() - 10, $this->GetY());
        $this->SetFont("Helvetica", "I", 8);
        $this->SetTextColor(90, 90, 90);
        $this->Cell(0, 8, "Generated by Miguel on " . date("F j, Y g:i A"), 0, 0, "L");
        $this->SetX(10);
        $this->Cell(0, 8, "Page " . $this->PageNo() . " of {nb}", 0, 0, "R");
        $this->SetTextColor(0, 0, 0);
    }

    function SectionTitle($title)
    {
        $this->SetFont("Helvetica", "B", 13);
        $this->SetTextColor(31, 78, 121);
        $this->Cell(0, 8, pdfText($title), 0, 1, "L");
        $this->SetTextColor(0, 0, 0);
    }

    function Paragraph($text)
    {
        $this->SetFont("Helvetica", "", 10.5);
        $this->MultiCell(0, 5, pdfText($text));
        $this->Ln(2);
    }

    function TableHeader()
    {
        $this->SetFont("Helvetica", "B", 10);
        $this->SetFillColor(31, 78, 121);
        $this->SetTextColor(255, 255, 255);
        $this->SetDrawColor(214, 222, 232);
        foreach ($this->columns as $col) {
            $this->Cell($col["width"], 8, $col["label"], 1, 0, "C", true);
        }
        $this->Ln();
        $this->SetTextColor(0, 0, 0);
    }

    function FitCell($width, $height, $text, $align, $fill)
    {
        $text = pdfText($text);
        while ($this->GetStringWidth($text) > $width - 3 && strlen($text) > 3) {
            $text = rtrim(substr($text, 0, -4)) . "...";
        }
        $this->Cell($width, $height, $text, 1, 0, $align, $fill);
    }

    function TableRows($rows)
    {
        $this->SetFont("Helvetica", "", 9.5);
        $fill = false;

        if (empty($rows)) {
            $this->SetFillColor(253, 236, 234);
            $this->Cell(array_sum(array_column($this->columns, "width")), 8, "No records found in the table.", 1, 1, "C", true);
            return;
        }

        foreach ($rows as $row) {
            if ($this->GetY() + 6.5 > $this->GetPageHeight() - 24) {
                $this->AddPage();
                $this->TableHeader();
                $this->SetFont("Helvetica", "", 9.5);
            }

            $this->SetFillColor(245, 248, 252);
            $values = [
                $row["game_id"],
                $row["title"],
                $row["genre"],
                $row["platform"],
                date("M j, Y", strtotime($row["release_date"])),
                "$" . number_format((float) $row["price"], 2),
                $row["rating"] . "/10",
                $row["multiplayer"] ? "Yes" : "No",
            ];

            foreach ($this->columns as $i => $col) {
                $this->FitCell($col["width"], 6.5, $values[$i], $col["align"], $fill);
            }
            $this->Ln();
            $fill = !$fill;
        }
    }

    function TableFooter($rows)
    {
        $count = count($rows);
        $avgPrice = $count ? array_sum(array_column($rows, "price")) / $count : 0;
        $avgRating = $count ? array_sum(array_column($rows, "rating")) / $count : 0;
        $multiplayer = count(array_filter(array_column($rows, "multiplayer")));

        $w = array_column($this->columns, "width");

        if ($this->GetY() + 8 > $this->GetPageHeight() - 24) {
            $this->AddPage();
            $this->TableHeader();
        }

        $this->SetFont("Helvetica", "B", 9.5);
        $this->SetFillColor(220, 230, 241);
        $this->Cell($w[0] + $w[1] + $w[2] + $w[3] + $w[4], 8, "Total games: $count", 1, 0, "L", true);
        $this->Cell($w[5], 8, "Avg $" . number_format($avgPrice, 2), 1, 0, "R", true);
        $this->Cell($w[6], 8, "Avg " . number_format($avgRating, 1), 1, 0, "R", true);
        $this->Cell($w[7], 8, "$multiplayer Yes", 1, 1, "C", true);
    }
}

